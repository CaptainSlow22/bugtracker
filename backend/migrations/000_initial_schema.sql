BEGIN;
SET LOCAL search_path TO public;

CREATE TABLE IF NOT EXISTS public.members (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firstname VARCHAR(80) NOT NULL
        CHECK (length(btrim(firstname)) > 0),
    lastname VARCHAR(80) NOT NULL
        CHECK (length(btrim(lastname)) > 0),
    email VARCHAR(254) NOT NULL
        CHECK (email = lower(btrim(email))),
    password TEXT NOT NULL,
    createdat TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT members_password_not_empty
        CHECK (length(password) > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS members_email_normalized_uidx
    ON public.members (lower(email));

CREATE TABLE IF NOT EXISTS public.projects (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(120) NOT NULL
        CHECK (length(btrim(title)) > 0),
    description VARCHAR(10000) NOT NULL
        CHECK (length(btrim(description)) > 0),
    createdat TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.projects_members (
    projectid INTEGER NOT NULL,
    memberid INTEGER NOT NULL,
    role TEXT NOT NULL DEFAULT 'member'
        CHECK (role IN ('owner', 'member')),
    createdat TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT projects_members_pkey
        PRIMARY KEY (projectid, memberid),
    CONSTRAINT projects_members_project_fk
        FOREIGN KEY (projectid)
        REFERENCES public.projects(id)
        ON DELETE CASCADE,
    CONSTRAINT projects_members_member_fk
        FOREIGN KEY (memberid)
        REFERENCES public.members(id)
        ON DELETE CASCADE
);

-- Adds role when upgrading a projects_members table created by an older schema.
ALTER TABLE public.projects_members
    ADD COLUMN IF NOT EXISTS role TEXT NOT NULL DEFAULT 'member';

CREATE INDEX IF NOT EXISTS projects_members_member_project_idx
    ON public.projects_members (memberid, projectid);

CREATE UNIQUE INDEX IF NOT EXISTS projects_members_project_member_uidx
    ON public.projects_members (projectid, memberid);

-- A project can have no more than one owner.
CREATE UNIQUE INDEX IF NOT EXISTS projects_members_one_owner_uidx
    ON public.projects_members (projectid)
    WHERE role = 'owner';

CREATE TABLE IF NOT EXISTS public.bugs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    projectid INTEGER NOT NULL,
    title VARCHAR(200) NOT NULL
        CHECK (length(btrim(title)) > 0),
    description VARCHAR(20000) NOT NULL
        CHECK (length(btrim(description)) > 0),
    resolution TEXT,
    status TEXT NOT NULL,
    priority TEXT NOT NULL,
    asignee INTEGER NOT NULL,
    reporter INTEGER NOT NULL,
    duedate DATE NOT NULL,
    createdat TIMESTAMPTZ NOT NULL DEFAULT now(),
    updatedat TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT bugs_project_fk
        FOREIGN KEY (projectid)
        REFERENCES public.projects(id)
        ON DELETE CASCADE,
    CONSTRAINT bugs_asignee_fk
        FOREIGN KEY (asignee)
        REFERENCES public.members(id)
        ON DELETE RESTRICT,
    CONSTRAINT bugs_reporter_fk
        FOREIGN KEY (reporter)
        REFERENCES public.members(id)
        ON DELETE RESTRICT,
    CONSTRAINT bugs_status_allowed_check
        CHECK (status IN ('TO DO', 'IN PROGRESS', 'DONE')),
    CONSTRAINT bugs_priority_allowed_check
        CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT bugs_resolution_length_check
        CHECK (
            resolution IS NULL
            OR length(btrim(resolution)) BETWEEN 1 AND 10000
        ),
    CONSTRAINT bugs_resolution_done_check
        CHECK (resolution IS NULL OR status = 'DONE')
);

-- Adds resolution when upgrading a bugs table created by an older schema.
ALTER TABLE public.bugs
    ADD COLUMN IF NOT EXISTS resolution TEXT;

CREATE INDEX IF NOT EXISTS bugs_project_id_desc_idx
    ON public.bugs (projectid, id DESC);

CREATE INDEX IF NOT EXISTS bugs_asignee_idx
    ON public.bugs (asignee);

CREATE INDEX IF NOT EXISTS bugs_reporter_idx
    ON public.bugs (reporter);

CREATE INDEX IF NOT EXISTS bugs_duedate_idx
    ON public.bugs (duedate);

CREATE TABLE IF NOT EXISTS public.comments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bugid INTEGER NOT NULL,
    memberid INTEGER NOT NULL,
    content VARCHAR(5000) NOT NULL
        CHECK (length(btrim(content)) > 0),
    createdat TIMESTAMPTZ NOT NULL DEFAULT now(),
    updatedat TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT comments_bug_fk
        FOREIGN KEY (bugid)
        REFERENCES public.bugs(id)
        ON DELETE CASCADE,
    CONSTRAINT comments_member_fk
        FOREIGN KEY (memberid)
        REFERENCES public.members(id)
        ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS comments_bug_created_idx
    ON public.comments (bugid, createdat, id);

CREATE INDEX IF NOT EXISTS comments_member_idx
    ON public.comments (memberid);

COMMIT;
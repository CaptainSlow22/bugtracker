-- Initial schema for a new Bugtracker PostgreSQL database.
-- Run this on an empty database. For an existing installation, use the
-- incremental migration 001_project_roles.sql instead.
BEGIN;

CREATE TABLE IF NOT EXISTS members (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firstname VARCHAR(80) NOT NULL CHECK (length(btrim(firstname)) > 0),
    lastname VARCHAR(80) NOT NULL CHECK (length(btrim(lastname)) > 0),
    email VARCHAR(254) NOT NULL CHECK (email = lower(btrim(email))),
    password TEXT NOT NULL,
    createdat TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT members_password_not_empty CHECK (length(password) > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS members_email_normalized_uidx
    ON members (lower(email));

CREATE TABLE IF NOT EXISTS projects (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(120) NOT NULL CHECK (length(btrim(title)) > 0),
    description VARCHAR(10000) NOT NULL CHECK (length(btrim(description)) > 0),
    createdat TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS projects_members (
    projectid INTEGER NOT NULL,
    memberid INTEGER NOT NULL,
    role TEXT NOT NULL DEFAULT 'member'
        CHECK (role IN ('owner', 'member')),
    createdat TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT projects_members_pkey PRIMARY KEY (projectid, memberid),
    CONSTRAINT projects_members_project_fk
        FOREIGN KEY (projectid) REFERENCES projects(id) ON DELETE CASCADE,
    CONSTRAINT projects_members_member_fk
        FOREIGN KEY (memberid) REFERENCES members(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS projects_members_member_project_idx
    ON projects_members (memberid, projectid);

-- At most one owner per project. Assign an owner when creating each project.
CREATE UNIQUE INDEX IF NOT EXISTS projects_members_one_owner_uidx
    ON projects_members (projectid)
    WHERE role = 'owner';

CREATE TABLE IF NOT EXISTS bugs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    projectid INTEGER NOT NULL,
    title VARCHAR(200) NOT NULL CHECK (length(btrim(title)) > 0),
    description VARCHAR(20000) NOT NULL CHECK (length(btrim(description)) > 0),
    status TEXT NOT NULL,
    priority TEXT NOT NULL,
    asignee INTEGER NOT NULL,
    reporter INTEGER NOT NULL,
    duedate DATE NOT NULL,
    createdat TIMESTAMPTZ NOT NULL DEFAULT now(),
    updatedat TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT bugs_project_fk
        FOREIGN KEY (projectid) REFERENCES projects(id) ON DELETE CASCADE,
    CONSTRAINT bugs_asignee_fk
        FOREIGN KEY (asignee) REFERENCES members(id) ON DELETE RESTRICT,
    CONSTRAINT bugs_reporter_fk
        FOREIGN KEY (reporter) REFERENCES members(id) ON DELETE RESTRICT,
    CONSTRAINT bugs_status_allowed_check
        CHECK (status IN ('TO DO', 'IN PROGRESS', 'DONE')),
    CONSTRAINT bugs_priority_allowed_check
        CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH'))
);

CREATE INDEX IF NOT EXISTS bugs_project_id_desc_idx
    ON bugs (projectid, id DESC);
CREATE INDEX IF NOT EXISTS bugs_asignee_idx
    ON bugs (asignee);
CREATE INDEX IF NOT EXISTS bugs_reporter_idx
    ON bugs (reporter);
CREATE INDEX IF NOT EXISTS bugs_duedate_idx
    ON bugs (duedate);

CREATE TABLE IF NOT EXISTS comments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bugid INTEGER NOT NULL,
    memberid INTEGER NOT NULL,
    content VARCHAR(5000) NOT NULL CHECK (length(btrim(content)) > 0),
    createdat TIMESTAMPTZ NOT NULL DEFAULT now(),
    updatedat TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT comments_bug_fk
        FOREIGN KEY (bugid) REFERENCES bugs(id) ON DELETE CASCADE,
    CONSTRAINT comments_member_fk
        FOREIGN KEY (memberid) REFERENCES members(id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS comments_bug_created_idx
    ON comments (bugid, createdat, id);
CREATE INDEX IF NOT EXISTS comments_member_idx
    ON comments (memberid);

-- Keep updatedat current for comment edits made by the API.
CREATE OR REPLACE FUNCTION set_updatedat()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updatedat = now();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS comments_set_updatedat ON comments;
CREATE TRIGGER comments_set_updatedat
    BEFORE UPDATE ON comments
    FOR EACH ROW
    EXECUTE FUNCTION set_updatedat();

COMMIT;
